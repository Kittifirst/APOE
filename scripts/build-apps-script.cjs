'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
// Reuse the same pure game rules in the browser and Apps Script V8 runtime.
const memory = read('games/memory/memory-game.js').split('    function load()')[0] +
    '    return { validate: validate, createDefault: createDefault };\n});\n';
const quiz = read('games/quiz/quiz-game.js').split('    function init(options)')[0] +
    '    return { validateState: validateState, DEFAULT_QUESTIONS: DEFAULT_QUESTIONS };\n}));\n';
const claw = require('../games/claw/claw-game.js');
const output = '// Generated by npm run build:apps-script. Do not edit this file directly.\n' +
    [read('games/wheel/wheel-engine.js'), read('games/wheel/wheel-state.js'), memory, quiz].join('\n') +
    '\nvar CLAW_DEFAULT_SETTINGS = ' + JSON.stringify(claw.DEFAULT_SETTINGS) + ';\n';
fs.mkdirSync(path.join(root, 'backend', 'google-apps-script'), { recursive: true });
fs.writeFileSync(path.join(root, 'backend', 'google-apps-script', 'GameModels.gs'), output);
console.log('Generated backend/google-apps-script/GameModels.gs');
